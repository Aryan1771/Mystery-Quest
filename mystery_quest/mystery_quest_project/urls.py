"""
URL configuration for mystery_quest_project project.
"""

from django.contrib import admin
from django.urls import path, include
from django.conf import settings
from django.conf.urls.static import static

urlpatterns = [
    path('admin/', admin.site.urls),
    path('accounts/', include('accounts.urls')),
    path('', include('investigation.urls')),
]

if settings.DEBUG:
    urlpatterns += static(settings.MEDIA_URL, document_root=settings.MEDIA_ROOT)
    urlpatterns += static(settings.STATIC_URL, document_root=settings.STATIC_ROOT)

# Admin Site Customization
admin.site.site_header = "Mystery Quest Investigation Headquarters"
admin.site.site_title = "Mystery Quest Admin Portal"
admin.site.index_title = "Federal Bureau of Detective Cases"
